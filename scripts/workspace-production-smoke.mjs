import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const out=resolve('.qa/workspace')
const browser=await chromium.launch({headless:true})
const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:900},acceptDownloads:true})
const page=await context.newPage()
await page.addInitScript(()=>{window.qaLiveWorkers=0;const Native=window.Worker;window.Worker=class extends Native{constructor(...args){super(...args);window.qaLiveWorkers++}terminate(){window.qaLiveWorkers--;super.terminate()}}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
try {
  await page.goto(process.env.WORKSPACE_PRODUCTION_QA_URL||'https://localhost:4173/')
  await page.locator('main.main').waitFor()
  await page.locator('.first-start-close').click()
  const path=resolve(out,'accordbook-qa-cedar-citrus-study-complete-development-history.accordbook')
  await page.locator('input[type=file][accept=".accordbook"]').nth(1).setInputFiles(path)
  await page.getByRole('status').filter({hasText:'Workspace imported.'}).waitFor()
  await page.getByRole('button',{name:'Export ▾',exact:true}).click()
  const wait=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export formula workspace',exact:true}).click()
  const download=await wait
  const file=JSON.parse(await readFile(await download.path(),'utf8'))
  assert.equal(file.type,'accordbook-workspace');assert.equal(file.versions.length,4);assert.equal(file.experiments.length,2)
  assert.ok(file.formula.releasedVersionId);assert.ok(file.formula.provenance)
  await page.locator('.tm-page-action').click();await page.locator('.tm-item').first().waitFor()
  assert.equal(await page.locator('.tm-item.manual').count(),3)
  await page.locator('.tm-item').filter({hasText:'Final QA release'}).locator('.tm-released').waitFor()
  await page.locator('.tm-close').click()
  await page.getByRole('button',{name:'Experiments',exact:true}).click()
  await page.locator('.experiment-list-item').filter({hasText:'QA Version Study'}).click()
  await page.locator('.experiment-detail').waitFor()
  assert.ok((await page.locator('.wide-workspace__context').innerText()).includes('BASE: V1'))
  await page.getByRole('button',{name:'A, 1 Branch',exact:true}).click()
  await page.getByRole('button',{name:'Record an evaluation',exact:true}).click()
  await page.getByLabel('What did you notice?',{exact:true}).fill('Production draft check')
  await page.getByRole('button',{name:'Export formula workspace',exact:true}).click()
  await page.locator('.experiment-detail').getByRole('alert').filter({hasText:'Save or cancel the open evaluation'}).waitFor()
  assert.equal(await page.getByLabel('What did you notice?',{exact:true}).inputValue(),'Production draft check')
  await page.getByRole('button',{name:'Save evaluation',exact:true}).click()
  const saved=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export formula workspace',exact:true}).click()
  const savedFile=JSON.parse(await readFile(await (await saved).path(),'utf8'))
  assert.ok(savedFile.experiments.flatMap(e=>e.variants).flatMap(v=>v.evaluations||[]).some(e=>e.observation==='Production draft check'))
  assert.deepEqual(errors,[])
  await page.screenshot({path:resolve(out,'production-experiments.png'),fullPage:true})
  assert.equal(await page.evaluate(()=>window.qaLiveWorkers),0)
  await page.reload();await page.locator('.formula-name').waitFor()
  const before=await page.evaluate(()=>localStorage.getItem('accordbook.activeFormulaId'))
  await page.locator('input[type=file][accept=".accordbook"]').nth(1).setInputFiles({name:'unsupported.accordbook',mimeType:'application/vnd.accordbook',buffer:Buffer.from(JSON.stringify({type:'accordbook-workspace',formatVersion:99}))})
  await page.getByRole('alert').filter({hasText:'This workspace version is not supported.'}).waitFor()
  assert.equal(await page.evaluate(()=>localStorage.getItem('accordbook.activeFormulaId')),before)
  assert.equal(await page.evaluate(()=>window.qaLiveWorkers),0)
  await writeFile(resolve(out,'production-smoke.json'),JSON.stringify({result:'PASS',browser:browser.version(),entry:'dist/index.html',versions:4,experiments:2,workerCleanup:true,workerErrorMapping:true,errors},null,2))
  console.log('PASS production build: UI import → download → Time Machine → Experiments; no page errors')
} finally {await browser.close()}
